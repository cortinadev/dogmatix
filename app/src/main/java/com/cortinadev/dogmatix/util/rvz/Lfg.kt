package com.cortinadev.dogmatix.util.rvz

/**
 * Lagged Fibonacci generator (f = xor, j = 32, k = 521) that GameCube and Wii mastering used for
 * the padding ("junk") between files. RVZ stores that padding as a 68-byte seed instead of the
 * bytes themselves.
 *
 * Written from the public description in Dolphin's `docs/WiaAndRvz.md` and the seed-recovery
 * algorithm of Dolphin's `LaggedFibonacciGenerator.cpp` (both CC0-1.0), cross-checked against
 * nod (`nod/src/util/lfg.rs`, Copyright 2021 Luke Street, MIT OR Apache-2.0).
 *
 * The buffer keeps the words already in "output form": bits 18..25 of the raw state are moved to
 * bits 16..23 (the quirk of shifting by 18 instead of 16 when emitting bytes). The transform is
 * linear over GF(2), so the xor steps work on output-form words directly and every word is
 * emitted as its four big-endian bytes.
 */
class Lfg {
    private val buffer = IntArray(K)
    private var position = 0 // byte position inside the current 521-word block

    /** Seeds from 17 raw seed words (the form RVZ stores, big endian on disk). */
    fun initWithSeed(seed: IntArray) {
        require(seed.size >= SEED_SIZE)
        System.arraycopy(seed, 0, buffer, 0, SEED_SIZE)
        position = 0
        init()
    }

    /** Seeds as the mastering tool did for [discOffset] (disc or partition-data offset). */
    fun initForOffset(discId: ByteArray, discNum: Int, discOffset: Long) {
        val seed = IntArray(SEED_SIZE)
        generateSeed(seed, discId, discNum, (discOffset / SECTOR_SIZE).toInt())
        initWithSeed(seed)
        skip((discOffset % SECTOR_SIZE).toInt())
    }

    private fun init() {
        for (i in SEED_SIZE until K) {
            buffer[i] = (buffer[i - SEED_SIZE] shl 23) xor (buffer[i - SEED_SIZE + 1] ushr 9) xor buffer[i - 1]
        }
        for (i in 0 until K) buffer[i] = toOutputForm(buffer[i])
        repeat(4) { forward() }
    }

    fun skip(bytes: Int) {
        position += bytes
        while (position >= K_BYTES) {
            forward()
            position -= K_BYTES
        }
    }

    fun fill(out: ByteArray, offset: Int, length: Int) {
        var o = offset
        val end = offset + length
        while (o < end) {
            if (position >= K_BYTES) {
                forward()
                position -= K_BYTES
            }
            val word = buffer[position ushr 2]
            out[o++] = (word ushr (24 - 8 * (position and 3))).toByte()
            position++
        }
    }

    /** How many bytes of [data] from [offset] equal the next generated bytes (stops at the first miss). */
    fun matchLength(data: ByteArray, offset: Int, length: Int): Int {
        var n = 0
        while (n < length) {
            if (position >= K_BYTES) {
                forward()
                position -= K_BYTES
            }
            val word = buffer[position ushr 2]
            if ((word ushr (24 - 8 * (position and 3))).toByte() != data[offset + n]) return n
            position++
            n++
        }
        return n
    }

    private fun forward() {
        for (i in 0 until J) buffer[i] = buffer[i] xor buffer[i + K - J]
        for (i in J until K) buffer[i] = buffer[i] xor buffer[i - J]
    }

    private fun backward() {
        for (i in K - 1 downTo J) buffer[i] = buffer[i] xor buffer[i - J]
        for (i in J - 1 downTo 0) buffer[i] = buffer[i] xor buffer[i + K - J]
    }

    /** [backward] restricted to the words in `start until end`. */
    private fun backwardRange(start: Int, end: Int) {
        val loopEnd = maxOf(J, start)
        var i = minOf(end, K)
        while (i > loopEnd) {
            i--
            buffer[i] = buffer[i] xor buffer[i - J]
        }
        i = minOf(end, J)
        while (i > start) {
            i--
            buffer[i] = buffer[i] xor buffer[i + K - J]
        }
    }

    /** [init] that checks the expanded state against words rebuilt from junk data. */
    private fun initCheckExisting(): Boolean {
        for (i in SEED_SIZE until K) {
            val calculated = (buffer[i - SEED_SIZE] shl 23) xor (buffer[i - SEED_SIZE + 1] ushr 9) xor buffer[i - 1]
            // Bits 16-17 of each word never reach the output, so they are not compared.
            val actual = (buffer[i] and 0xFF00FFFF.toInt()) or ((buffer[i] shl 2) and 0x00FC0000)
            if ((calculated and 0xFFFCFFFF.toInt()) != actual) return false
            buffer[i] = calculated
        }
        for (i in 0 until K) buffer[i] = toOutputForm(buffer[i])
        repeat(4) { forward() }
        return true
    }

    private fun reinitialize(seedOut: IntArray): Boolean {
        repeat(4) { backward() }
        for (i in 0 until SEED_SIZE) {
            buffer[i] = (buffer[i] and 0xFF00FFFF.toInt()) or
                ((buffer[i] shl 2) and 0x00FC0000) or
                (((buffer[i + 16] xor buffer[i + 15]) shl 9) and 0x00030000)
        }
        System.arraycopy(buffer, 0, seedOut, 0, SEED_SIZE)
        return initCheckExisting()
    }

    /**
     * Rebuilds the seed of junk data that starts [streamOffset] bytes into its 32 KiB sector
     * without knowing the disc ID. Needs [K_BYTES] (+ up to 3 alignment bytes) of junk. Returns
     * how many bytes from [offset] the recovered seed reproduces (0 = not junk).
     */
    fun recoverSeed(data: ByteArray, offset: Int, length: Int, streamOffset: Int, seedOut: IntArray): Int {
        val skipBytes = (4 - (streamOffset and 3)) and 3
        if (length < skipBytes + K_BYTES) return 0
        val wordOffset = (streamOffset + skipBytes) / 4
        val modK = wordOffset % K
        val divK = wordOffset / K
        var p = offset + skipBytes
        for (i in 0 until K) {
            val word = readIntBE(data, p)
            p += 4
            if ((word and 0x00C00000) != ((word ushr 2) and 0x00C00000)) return 0
            buffer[(modK + i) % K] = word
        }
        backwardRange(0, modK)
        repeat(divK) { backward() }
        if (!reinitialize(seedOut)) return 0
        // Check through the same path readers use.
        initWithSeed(seedOut)
        skip(streamOffset)
        return matchLength(data, offset, minOf(length, SECTOR_SIZE - streamOffset))
    }

    companion object {
        const val K = 521
        const val J = 32
        const val K_BYTES = K * 4
        const val SEED_SIZE = 17
        const val SEED_BYTES = SEED_SIZE * 4
        const val SECTOR_SIZE = 0x8000

        private fun toOutputForm(x: Int): Int = (x and 0xFF00FFFF.toInt()) or ((x ushr 2) and 0x00FF0000)

        /** Seed the mastering tool used for junk in [sector] (32 KiB units) of a disc or partition. */
        fun generateSeed(out: IntArray, discId: ByteArray, discNum: Int, sector: Int) {
            val b0 = discId[0].toInt() and 0xFF
            val b1 = discId[1].toInt() and 0xFF
            val b2 = discId[2].toInt() and 0xFF
            val b3 = discId[3].toInt() and 0xFF
            val seed = ((b2 shl 24) or (b1 shl 16) or (((b3 + b2) and 0xFF) shl 8) or ((b0 + b1) and 0xFF)) xor
                (discNum and 0xFF)
            var n = (seed * 0x260BCD5) xor (sector * 0x1EF29123)
            for (i in 0 until SEED_SIZE) {
                var v = 0
                repeat(J) {
                    n = n * 0x5D588B65 + 1
                    v = (v ushr 1) or (n and 0x80000000.toInt())
                }
                out[i] = v
            }
            out[16] = out[16] xor ((out[0] ushr 9) xor (out[16] shl 23))
        }

        internal fun readIntBE(b: ByteArray, p: Int): Int =
            ((b[p].toInt() and 0xFF) shl 24) or ((b[p + 1].toInt() and 0xFF) shl 16) or
                ((b[p + 2].toInt() and 0xFF) shl 8) or (b[p + 3].toInt() and 0xFF)
    }
}
